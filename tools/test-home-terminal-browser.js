async (page) => {
    await page.goto('http://127.0.0.1:8000/');
    const input = page.getByRole('textbox', { name: 'Terminal command' });
    const output = page.getByRole('log', { name: 'Terminal output' });
    const check = (ok, message) => { if (!ok) throw new Error(message); };
    const run = async value => {
        await input.fill(value);
        await input.press('Enter');
        await page.waitForFunction(() => !document.getElementById('terminal-input').readOnly);
        return output.locator('.explorer-result').last().innerText();
    };
    check((await run('cd books')).includes('~/books'), 'cd failed');
    check((await run('ls --top -l')).includes('10/10'), 'ratings missing');
    check((await run('ls --tag "time loop" -n 1 --page 2')).includes('Showing 2-2'), 'pagination failed');
    check((await run('cat mother-of-learning')).includes('Zorian'), 'preview failed');
    await input.press('ArrowUp');
    check(await input.inputValue() === 'cat mother-of-learning', 'history failed');
    await input.press('ArrowDown');
    check(await input.inputValue() === '', 'history draft failed');
    await input.fill('open moth');
    await input.press('Tab');
    check(await input.inputValue() === 'open mother-of-learning', 'completion failed');
    await input.press('Tab');
    check(await page.getByRole('button', { name: 'Run', exact: true }).evaluate(el => el === document.activeElement), 'Tab focus is trapped');
    await input.fill('open mother-of-learning');
    await Promise.all([page.waitForURL('**/books.html#book-1'), input.press('Enter')]);
    await page.getByRole('heading', { name: 'Mother of Learning', exact: true }).waitFor();
    await page.goto('http://127.0.0.1:8000/');
    await run('cd projects');
    check((await run('ls --tag AI')).includes('tracetick'), 'project filter failed');
    await input.fill('open crux');
    await Promise.all([page.waitForURL('**/projects.html#project-crux'), input.press('Enter')]);
    await page.getByRole('heading', { name: 'Crux', exact: true }).waitFor();
    await page.goto('http://127.0.0.1:8000/');
    await input.fill('open /resume/achievements');
    await Promise.all([page.waitForURL('**/resume.html#achievements'), input.press('Enter')]);
    await page.goto('http://127.0.0.1:8000/');
    await run('<img src=x onerror=alert(1)>');
    check(await output.locator('img').count() === 0, 'output interpreted HTML');
    await input.press('Control+l');
    check(await output.innerText() === '', 'Ctrl+L failed');
    await run('help');
    await page.setViewportSize({ width: 1440, height: 1050 });
    await page.getByRole('region', { name: 'Explore the site' }).screenshot({ path: 'output/playwright/terminal-desktop.png' });
    await page.setViewportSize({ width: 390, height: 844 });
    await run('ls /projects -l -n 3');
    check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'mobile horizontal overflow');
    await page.getByRole('region', { name: 'Explore the site' }).screenshot({ path: 'output/playwright/terminal-mobile.png' });
    return 'Passed browsing, filters, pagination, previews, history, completion, focus navigation, book/project/resume links, safe output, and mobile width.';
}
